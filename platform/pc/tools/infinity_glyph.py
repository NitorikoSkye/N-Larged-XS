#!/usr/bin/env python3
"""Draws the infinity sign Gameplay's infinite lives shows for the lives
count (hud_hook.cpp, borders.c), in the HUD digits' look: a thick yellow
stroke, orange on its upper left, a dark brown outline and a darker
shadow under it. Its pixels are the HUD digits' palette indices (4
yellow, 8 orange-yellow, 10 orange, 5 brown, 6 dark), so the game's own
palette colours it.

    infinity_glyph.py > platform/pc/src/infinity_glyph.h

Two sizes: the HUD's (32x16, one 32x16 OBJ beside the lives icon) and
the left border's, by its small digits (20x10, a thinner stroke so its
loops stay open)."""
import math


def glyph(w, h, a, ys, r, o):
    cx, cy = w / 2 - 0.1, h / 2 - 0.1
    pts = []
    for i in range(3000):
        t = 2 * math.pi * i / 3000
        d = 1 + math.sin(t) ** 2  # the lemniscate of Bernoulli
        pts.append((cx + a * math.cos(t) / d, cy + ys * a * math.sin(t) * math.cos(t) / d))
    rows = []
    for y in range(h):
        row = ""
        for x in range(w):
            px, py = x + 0.5, y + 0.5
            best = min(pts, key=lambda p: (px - p[0]) ** 2 + (py - p[1]) ** 2)
            nx, ny = px - best[0], py - best[1]
            d = math.hypot(nx, ny)
            v = 0
            if d <= r:
                s = (-nx - ny * 0.8) / max(d, 1e-6)  # facing up and left
                if d > r * 0.43 and s > 0.45:
                    v = 10 if d > r * 0.73 else 8
                elif d > r * 0.65 and s > -0.1:
                    v = 8
                else:
                    v = 4
            elif d <= r + o:
                v = 6 if ny > 0.6 * d and d > r + 0.4 else 5
            row += "%X" % v
        rows.append(row)
    return rows


def emit(name, rows):
    print("static const char %s[%d][%d] = {" % (name, len(rows), len(rows[0]) + 1))
    for row in rows:
        print('    "%s",' % row)
    print("};")


print("/* Generated by platform/pc/tools/infinity_glyph.py: the HUD digits'")
print(" * palette indices, 0 clear. */")
emit("sInfinityLarge", glyph(32, 16, 12.7, 1.15, 1.85, 1.1))
emit("sInfinitySmall", glyph(20, 10, 8.4, 1.25, 1.0, 0.85))
